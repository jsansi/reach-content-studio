// Builds the BTL design-system package: dist/index.js (+ .d.ts), dist/btl.css and dist/fonts/.
// Tokens come from studio/brands/btl.js (the renderer's source of truth); primitives CSS from src/btl.css.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { btl, unit } from '../../studio/brands/btl.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const dist = path.join(here, 'dist');
fs.rmSync(dist, { recursive: true, force: true });
fs.mkdirSync(path.join(dist, 'fonts'), { recursive: true });

// Fonts (Noto Sans, manual p. 18)
const fontDir = path.join(root, btl.fontDir);
const fonts = fs.readdirSync(fontDir).filter((f) => f.endsWith('.woff2'));
for (const f of fonts) fs.copyFileSync(path.join(fontDir, f), path.join(dist, 'fonts', f));
const faces = fonts
  .map((f) => {
    const [, ext, weight] = f.match(/noto-sans-latin(-ext)?-(\d+)-normal/) ?? [];
    const range = ext ? '\n  unicode-range: U+0100-024F, U+1E00-1EFF;' : '';
    return `@font-face {\n  font-family: 'Noto Sans';\n  font-style: normal;\n  font-weight: ${weight};\n  font-display: block;\n  src: url('./fonts/${f}') format('woff2');${range}\n}`;
  })
  .join('\n');

// Tokens
const c = btl.colors;
const u = unit(btl);
const tokens = `:root {
  --btl-enterprise: ${c.enterpriseBlue};
  --btl-dark: ${c.darkBlue};
  --btl-sky: ${c.skyBlue};
  --btl-white: ${c.white};
  --btl-u: ${u.toFixed(2)}px; /* half the logo height (manual p. 5) */
  --btl-m: ${Math.round(2 * u)}px; /* 2 U: distance to the canvas edge */
  --btl-logo-width: ${btl.logoWidth}px;
  --btl-min-text: 30px; /* REACH mobile legibility floor */
}`;
const css = fs.readFileSync(path.join(here, 'src/btl.css'), 'utf8');
fs.writeFileSync(path.join(dist, 'btl.css'), `/* Generated by design-system/btl/build.mjs — edit src/btl.css or studio/brands/btl.js. */\n${faces}\n\n${tokens}\n\n${css}`);

// JS
await build({
  entryPoints: [path.join(here, 'src/index.ts')],
  bundle: true,
  format: 'esm',
  target: 'es2020',
  outfile: path.join(dist, 'index.js'),
  external: ['react', 'react/jsx-runtime'],
  jsx: 'automatic',
  loader: { '.svg': 'text', '.png': 'dataurl', '.jpg': 'dataurl' },
  logLevel: 'warning',
});

// Types
execFileSync(process.execPath, [path.join(root, 'node_modules/typescript/bin/tsc'), '-p', path.join(here, 'tsconfig.json')], { stdio: 'inherit' });
console.log('built', path.relative(root, dist));
